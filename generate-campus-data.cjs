const fs=require('fs'),assert=require('assert/strict');
const structure=JSON.parse(fs.readFileSync('campus-structure.json','utf8'));
const locations=structure.buildings.flatMap(b=>structure.floors.flatMap(f=>f.rooms.map(room=>{
 const token=room==="Dean's Office"?'DEAN':room==='Faculty Room'?'FACULTY':room.replace('Room ','');
 return {building:b.name,floor:f.label,floor_number:f.number,room,station_id:`SSU-${b.code}-${f.number}-${token}`,status:'offline',room_status:'normal'};
})));
assert.equal(locations.length,102);assert.equal(new Set(locations.map(r=>r.station_id)).size,102);assert.equal(new Set(locations.map(r=>[r.building,r.floor_number,r.room].join(':'))).size,102);
fs.writeFileSync('campus-data.js','/* Generated by generate-campus-data.cjs. New locations remain offline until hardware reports online. */\nconst CAMPUS_STRUCTURE='+JSON.stringify(structure,null,2)+';\nconst CAMPUS_STATION_LOCATIONS='+JSON.stringify(locations,null,2)+';\n');
fs.mkdirSync('database',{recursive:true});
const cols=['building','floor_number','floor','room','station_id','status','room_status'];
const csv=value=>'"'+String(value).replaceAll('"','""')+'"';
fs.writeFileSync('database/station-locations.csv',cols.join(',')+'\n'+locations.map(r=>cols.map(c=>csv(r[c])).join(',')).join('\n')+'\n');
fs.writeFileSync('database/station-locations.json',JSON.stringify(locations,null,2)+'\n');
console.log('Generated 6 buildings, 18 building floors, 102 room/station locations.');
